if ( ! function_exists( 'zc_demo_add_comments' ) ) :
	/**
	 * افزودن دیدگاه‌های نمونه به یک نوشته.
	 *
	 * @param int    $post_id شناسه نوشته.
	 * @param int    $index   ترتیب نوشته.
	 * @param string $date    تاریخ انتشار (GMT).
	 * @return void
	 */
	function zc_demo_add_comments( $post_id, $index, $date ) {
		$sets = zc_demo_comments();
		if ( empty( $sets[ $index ] ) ) {
			return;
		}

		$admin     = get_userdata( get_current_user_id() ? get_current_user_id() : 1 );
		$base_time = strtotime( $date . ' +0000' );
		$offset    = 0;

		foreach ( $sets[ $index ] as $comment ) {
			$offset += 7 * HOUR_IN_SECONDS;
			$time    = gmdate( 'Y-m-d H:i:s', min( time(), $base_time + $offset ) );

			$comment_id = wp_insert_comment(
				array(
					'comment_post_ID'      => $post_id,
					'comment_author'       => $comment[0],
					'comment_author_email' => 'demo+' . md5( $comment[0] ) . '@example.com',
					'comment_content'      => $comment[1],
					'comment_approved'     => 1,
					'comment_date_gmt'     => $time,
					'comment_date'         => get_date_from_gmt( $time ),
				)
			);
			if ( $comment_id ) {
				update_comment_meta( (int) $comment_id, '_zc_demo_comment', '1' );
			}

			if ( $comment_id && '' !== $comment[2] ) {
				$reply_time = gmdate( 'Y-m-d H:i:s', min( time(), $base_time + $offset + 3 * HOUR_IN_SECONDS ) );
				$reply_id   = wp_insert_comment(
					array(
						'comment_post_ID'      => $post_id,
						'comment_parent'       => (int) $comment_id,
						'comment_author'       => 'مریم جمالی',
						'comment_author_email' => $admin ? $admin->user_email : '',
						'user_id'              => $admin ? (int) $admin->ID : 0,
						'comment_content'      => $comment[2],
						'comment_approved'     => 1,
						'comment_date_gmt'     => $reply_time,
						'comment_date'         => get_date_from_gmt( $reply_time ),
					)
				);
				if ( $reply_id ) {
					update_comment_meta( (int) $reply_id, '_zc_demo_comment', '1' );
				}

				// پاسخ سطح دوم (ادامه‌ی گفتگو توسط همان مخاطب) برای نمایش رشته‌ی تودرتو.
				if ( $reply_id && ! empty( $comment[3] ) ) {
					$follow_time = gmdate( 'Y-m-d H:i:s', min( time(), $base_time + $offset + 5 * HOUR_IN_SECONDS ) );
					$follow_id   = wp_insert_comment(
						array(
							'comment_post_ID'      => $post_id,
							'comment_parent'       => (int) $reply_id,
							'comment_author'       => $comment[0],
							'comment_author_email' => 'demo+' . md5( $comment[0] ) . '@example.com',
							'comment_content'      => $comment[3],
							'comment_approved'     => 1,
							'comment_date_gmt'     => $follow_time,
							'comment_date'         => get_date_from_gmt( $follow_time ),
						)
					);
					if ( $follow_id ) {
						update_comment_meta( (int) $follow_id, '_zc_demo_comment', '1' );
					}
				}
			}
		}
	}
